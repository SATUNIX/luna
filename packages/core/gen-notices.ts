// Strip the leading "# SOURCE" heading and surrounding blank lines so only the
// upstream/date/changes content is embedded.
function sourceBody(raw: string): string {
  const lines = raw.replace(/\r\n/g, "\n").split("\n");
  let i = 0;
  while (lines[i]?.trim() === "") i++;
  if (/^#\s+/.test(lines[i] ?? "")) i++;
  while (lines[i]?.trim() === "") i++;
  return lines.slice(i).join("\n").trimEnd();
}

