#!/usr/bin/env node
/**
 * Generate docs/capability-matrix.md: profile -> extensions -> task class.
 * Built from profiles/*.json + each extension.json + packages/core/sources.json (externals).
 * Deterministic; --check mode lets verify.ts diff a fresh regen. (Epic 3 Sprint 3.3.)
 *
 * Usage:
 *   node packages/core/capability-matrix.ts            # write docs/capability-matrix.md
 *   node packages/core/capability-matrix.ts --check    # exit 1 if committed doc is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isRecord, parseJson } from "./lib/guard.ts";
import { WORKSPACE_ROOT, PROFILES_DIR, FIRST_PARTY_DIR, THIRD_PARTY_DIR, SOURCES_PATH } from "./lib/paths.ts";
import { loadProfileDef } from "./lib/profiles.ts";
import { readSources } from "./lib/sources.ts";

const ROOT = WORKSPACE_ROOT;
const DOC_PATH = path.join(ROOT, "docs", "capability-matrix.md");

const PROFILE_ORDER = ["lite", "quick", "balanced", "long-horizon", "autonomous", "self-improving", "pentest"];

// Profile-level metadata (task class + tier band). Fixed, documented set of shipped profiles.
const PROFILE_META: Readonly<Record<string, { taskClass: string; tiers: string }>> = {
  lite: { taskClass: "Low-context / small local models", tiers: "T0–T1" },
  quick: { taskClass: "Quick fix", tiers: "T0–T1" },
  balanced: { taskClass: "Daily coding", tiers: "T0–T2" },
  "long-horizon": { taskClass: "Multi-hour / multi-day", tiers: "T0–T3" },
  autonomous: { taskClass: "Set-and-walk-away", tiers: "T0–T3" },
  "self-improving": { taskClass: "Full / self-improving (experimental)", tiers: "T0–T4" },
  pentest: { taskClass: "Security engagement (strict)", tiers: "T0–T3+" },
};

type ProfileDef = ReturnType<typeof loadProfileDef>;

/** What the matrix shows of one extension. */
interface ExtensionMeta {
  category: string | undefined;
  status: string | undefined;
  avenue?: string;
}

function loadProfiles(): Map<string, ProfileDef> {
  const out = new Map<string, ProfileDef>();
  for (const name of PROFILE_ORDER) {
    const p = path.join(PROFILES_DIR, `${name}.json`);
    if (fs.existsSync(p)) out.set(name, loadProfileDef(name, PROFILES_DIR));
  }
  return out;
}

/** The include list of a profile (its extension names). */
function includeOf(profile: ProfileDef | undefined): string[] {
  const include: unknown = profile?.include;
  return Array.isArray(include) ? include.filter((name): name is string => typeof name === "string") : [];
}

function loadManifests(): Map<string, ExtensionMeta> {
  const meta = new Map<string, ExtensionMeta>(); // name -> { category, status, avenue }
  for (const { dir, avenue } of [
    { dir: FIRST_PARTY_DIR, avenue: "first-party" },
    { dir: THIRD_PARTY_DIR, avenue: "third-party" },
  ]) {
    if (!fs.existsSync(dir)) continue;
    for (const n of fs.readdirSync(dir)) {
      if (n.startsWith("_")) continue;
      const mp = path.join(dir, n, "extension.json");
      if (!fs.existsSync(mp)) continue;
      const m = parseJson(fs.readFileSync(mp, "utf8"));
      if (!isRecord(m)) {
        console.warn(`[capability-matrix] WARN: ignoring non-object manifest: ${path.relative(ROOT, mp)}`);
        continue;
      }
      // A manifest without a string name can match no profile entry (those are strings).
      if (typeof m.name !== "string") continue;
      const text = (value: unknown): string | undefined => (typeof value === "string" ? value : undefined);
      meta.set(m.name, { category: text(m.category), status: text(m.status), avenue });
    }
  }
  const sourcesPath = SOURCES_PATH;
  if (fs.existsSync(sourcesPath)) {
    for (const e of readSources(sourcesPath).external) {
      for (const name of e.provides ?? [e.name]) {
        if (!meta.has(name)) meta.set(name, { category: "external", status: "external", avenue: "external" });
      }
    }
  }
  return meta;
}

function render(): string {
  const profiles = loadProfiles();
  const manifests = loadManifests();

  // Membership set per extension.
  const membership = new Map<string, Set<string>>();
  for (const name of PROFILE_ORDER) {
    for (const ext of includeOf(profiles.get(name))) {
      const set = membership.get(ext) ?? new Set<string>();
      set.add(name);
      membership.set(ext, set);
    }
  }

  const lines = [
    "# Capability Matrix",
    "",
    "> Auto-generated by `packages/core/capability-matrix.ts` from `profiles/*.json`, each",
    "> `extension.json`, and `packages/core/sources.json`. Do not hand-edit; run `npm run catalog`.",
    "",
    "## Profiles at a glance",
    "",
    "| Profile | Task class | Tiers | Extensions |",
    "|---|---|---|---|",
  ];
  for (const name of PROFILE_ORDER) {
    const p = profiles.get(name);
    if (!p) continue;
    const m = PROFILE_META[name] ?? { taskClass: "", tiers: "" };
    lines.push(`| \`${name}\` | ${m.taskClass} | ${m.tiers} | ${includeOf(p).length} |`);
  }
  lines.push("");

  // Extension x profile matrix, grouped by category.
  lines.push("## Extension × profile", "");
  lines.push(`| Extension | Category | Status | ${PROFILE_ORDER.map((p) => p.replace("-", "&#8209;")).join(" | ")} |`);
  lines.push(`|---|---|---|${PROFILE_ORDER.map(() => ":-:").join("|")}|`);

  const names = [...membership.keys()].sort((a, b) => {
    const ca = manifests.get(a)?.category || "zzz";
    const cb = manifests.get(b)?.category || "zzz";
    return ca === cb ? a.localeCompare(b) : ca.localeCompare(cb);
  });
  for (const name of names) {
    const meta = manifests.get(name) ?? { category: "external", status: "external" };
    const cells = PROFILE_ORDER.map((p) => (membership.get(name)?.has(p) ? "✓" : "·"));
    lines.push(`| \`${name}\` | ${String(meta.category)} | ${String(meta.status)} | ${cells.join(" | ")} |`);
  }
  lines.push("");
  lines.push(
    "Legend: ✓ enabled in that profile · `·` not included. `experimental`/`stub` extensions",
    "appear only in the experimental `self-improving` profile (see `SECURITY.md` and the",
    "roadmap). Externals (`pi-*`) install from `packages/core/sources.json`.",
    "",
  );
  return lines.join("\n");
}

export function capabilityMatrixContent(): string {
  return render();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const content = capabilityMatrixContent();
  if (check) {
    const current = fs.existsSync(DOC_PATH) ? fs.readFileSync(DOC_PATH, "utf8") : "";
    if (current !== content) {
      console.error("[capability-matrix] STALE: docs/capability-matrix.md differs from a fresh regen. Run: npm run catalog");
      process.exit(1);
    }
    console.log("[capability-matrix] OK: docs/capability-matrix.md is up to date.");
  } else {
    fs.writeFileSync(DOC_PATH, content);
    console.log(`[capability-matrix] Wrote ${path.relative(ROOT, DOC_PATH)}.`);
  }
}
