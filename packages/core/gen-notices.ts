#!/usr/bin/env node
/**
 * Generate THIRD_PARTY_NOTICES.md from the vendored extensions' SOURCE.md files.
 *
 * Deterministic: no timestamps, no unordered iteration. Exports `noticesContent()`
 * so `verify.ts` can fail on drift, and can be run directly:
 *
 *   node packages/core/gen-notices.ts            # write the file
 *   node packages/core/gen-notices.ts --check    # exit 1 if the committed file is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { WORKSPACE_ROOT, THIRD_PARTY_DIR } from "./lib/paths.ts";

const ROOT = WORKSPACE_ROOT;
const NOTICES_PATH = path.join(ROOT, "THIRD_PARTY_NOTICES.md");

